def build_audit():
    original={r['text'].strip().casefold() for rows in build_dataset().values() for r in rows}
    audit=[]
    for label,block in BLOCKS.items():
        for line in block.splitlines():
            language,text=line.split('|',1)
            if text.strip().casefold() in original:raise ValueError('Repeated example')
            original.add(text.strip().casefold())
            audit.append({'id':hashlib.sha256(text.encode()).hexdigest()[:12],'text':text,'label':label,'label_id':LABELS.index(label),'language':language,'source':'assistant_authored_synthetic_final_audit','split':'test'})
    return audit
