def build_dataset():
    data = {s: [] for s in ("train", "validation", "test")}
    seen = set()
    for label, blocks in EXAMPLES.items():
        for split, block in zip(data, blocks):
            for line in block.splitlines():
                language, text = line.split("|", 1)
                normalized = text.strip().casefold()
                if normalized in seen:
                    raise ValueError("Repeated example across splits")
                seen.add(normalized)
                data[split].append({"id": hashlib.sha256(text.encode()).hexdigest()[:12], "text":text,
                                    "label":label,"label_id":LABELS.index(label),"language":language,
                                    "source":"authored_synthetic","split":split})
    return data

if __name__ == "__main__":
    root = Path(__file__).parent / "data"
    root.mkdir(exist_ok=True)
    for split, rows in build_dataset().items():
        (root / f"{split}.jsonl").write_text("".join(json.dumps(r,ensure_ascii=False)+"\n" for r in rows),encoding="utf-8")
        print(split, len(rows))
