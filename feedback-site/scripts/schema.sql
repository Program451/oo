PRAGMA foreign_keys=ON;
PRAGMA journal_mode=WAL;
CREATE TABLE IF NOT EXISTS surveys(id TEXT PRIMARY KEY,title TEXT NOT NULL,kind TEXT NOT NULL,dishes TEXT NOT NULL,created_at TEXT NOT NULL,closes_at TEXT NOT NULL,closed INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS responses(seq INTEGER PRIMARY KEY AUTOINCREMENT,id TEXT NOT NULL UNIQUE,survey_id TEXT NOT NULL REFERENCES surveys(id),nonce TEXT NOT NULL,dish TEXT NOT NULL,body TEXT NOT NULL,created_at TEXT NOT NULL);
CREATE UNIQUE INDEX IF NOT EXISTS response_once ON responses(survey_id,nonce);
CREATE INDEX IF NOT EXISTS response_survey ON responses(survey_id);
CREATE TABLE IF NOT EXISTS rate_limits(id TEXT PRIMARY KEY,count INTEGER NOT NULL,expires INTEGER NOT NULL);
